export async function POST() {
  try {
    await connectToDatabase();

    // 1. Seed EDO
    await EdoLecturerEvaluation.deleteMany({});
    const seededEdo = await EdoLecturerEvaluation.insertMany(initialEdoLecturers);

    // 2. Seed EKA
    await EkaServiceEvaluation.deleteMany({});
    const seededEka = await EkaServiceEvaluation.insertMany(initialEkaServices);

    // 3. Seed Tracer Study
    await TracerStudyResponse.deleteMany({});
    const seededTracer = await TracerStudyResponse.insertMany(initialTracerResponses);

    // 4. Seed Employer Survey
    await EmployerSurveyResponse.deleteMany({});
    const seededEmployer = await EmployerSurveyResponse.insertMany(initialEmployerResponses);

    // 5. Auto-Recalculate and update IKU 2 in Achievement collection
    const totalTracer = seededTracer.length;
    const successfulTracer = seededTracer.filter((r) =>
      ["BEKERJA", "WIRAUSAHA", "STUDI_LANJUT"].includes(r.status)
    ).length;
    const absorptionRate =
      totalTracer > 0 ? Math.round((successfulTracer / totalTracer) * 100 * 10) / 10 : 0;

    const iku2Meta = await IKUMetadata.findOne({ code: "IKU 2" });
    let iku2Updated = false;

    if (iku2Meta) {
      // Upsert Achievement for year 2026, quarter 4 (or quarter 1)
      await Achievement.findOneAndUpdate(
        { ikuId: iku2Meta._id, year: 2026, quarter: 4 },
        {
          ikuId: iku2Meta._id,
          year: 2026,
          quarter: 4,
          value: absorptionRate,
          status: "Disetujui",
          documentUrl: "/dashboard/evaluations",
        },
        { upsert: true, new: true }
      );
      iku2Updated = true;
    }

    return NextResponse.json({
      success: true,
      message: "Data Evaluasi (EDO, EKA, Tracer Study, Survei Pengguna) berhasil disemai & disinkronkan ke IKU 2",
      stats: {
        edoCount: seededEdo.length,
        ekaCount: seededEka.length,
        tracerCount: seededTracer.length,
        employerCount: seededEmployer.length,
        tracerAbsorptionRate: `${absorptionRate}%`,
        iku2Updated,
      },
    });
  } catch (error: unknown) {
    const err = error as Error;
    console.error("Error seeding evaluation data:", err);
    return NextResponse.json(
      { success: false, error: err.message || "Failed to seed evaluation data" },
      { status: 500 }
    );
  }
}

export async function GET() {
  return POST();
}
